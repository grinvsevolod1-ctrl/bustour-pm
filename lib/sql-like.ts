/**
 * Экранирует спецсимволы SQL LIKE (%, _, \) в динамической части шаблона,
 * чтобы строка сопоставлялась буквально, а не как маска.
 *
 * Зачем: слаги теперь могут содержать «_» (например, sankt_peterburg). В LIKE
 * «_» — это подстановочный символ «любой один символ», поэтому без экранирования
 * шаблон `city:bus:sankt_peterburg.%` ошибочно совпадал бы с `city:bus:sankt-peterburg.*`.
 * Это ломало переименование URL (ложная коллизия) и грозило лишними удалениями.
 *
 * В PostgreSQL символ экранирования LIKE по умолчанию — обратный слэш, поэтому
 * достаточно вернуть экранированную строку и использовать её в обычном like().
 */
export function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (ch) => `\\${ch}`)
}
